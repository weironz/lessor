//! 让 cargo 知道前端产物也是这个 crate 的输入。
//!
//! `ui.rs` 用 rust-embed 在**编译期**把 `ui/dist` 打进二进制。但 cargo 只
//! 盯着 `.rs` 文件 —— 前端改了、`ui/dist` 变了，只要没有一行 Rust 代码变动，
//! 它就认为不用重编，于是宏不会重新展开，二进制里还是上一次的界面。
//!
//! 症状特别误导：`cargo build` 明明跑了几十秒（时间花在依赖上），起来的却
//! 还是旧界面 —— 会让人以为是浏览器缓存或者前端没构建。实际踩过一次。
//!
//! CI 每次都是干净构建，所以只有本地开发会中招。
fn main() {
    println!("cargo:rerun-if-changed=../../ui/dist");
}
